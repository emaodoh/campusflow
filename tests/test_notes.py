from unittest.mock import patch

import pytest

from campusflow.notes import add_note, note_display

MODULE = "campusflow.notes"


@pytest.fixture
def stored_tickets():
    """What load_ticket() returns: the 'database'."""
    return [
        {"id": "T1", "status": "open", "notes": [
            {"note_id": "N1", "author": "Alice", "message": "first note"}]},
        {"id": "T2", "status": "resolved", "notes": []},
        {"id": "T3", "status": "in_progress", "notes": []},
    ]


@pytest.fixture
def mocks(stored_tickets):
    """Patch everything notes.py imports, where notes.py looks the names up."""

    def fake_find(ticket_id):
        # IDs are generated by the program, so they must match exactly
        for ticket in stored_tickets:
            if ticket["id"] == ticket_id:
                return ticket
        raise ValueError("Ticket not found")

    with patch(f"{MODULE}.load_ticket", return_value=stored_tickets) as load, \
         patch(f"{MODULE}.save_ticket") as save, \
         patch(f"{MODULE}.find_ticket", side_effect=fake_find) as find, \
         patch(f"{MODULE}.generate_note_id", return_value="N9") as gen, \
         patch(f"{MODULE}.validate_note_entry") as validate:
        yield {"load": load, "save": save, "find": find,
               "gen": gen, "validate": validate}


# ---------- add_note: success ----------

def test_add_note_success_message(mocks):
    assert add_note("T1", "Bob", "looking into it") == "Note added successfully! "


def test_add_note_appends_note_with_generated_id(mocks):
    add_note("T1", "Bob", "looking into it")

    saved = mocks["save"].call_args[0][0]
    t1 = next(t for t in saved if t["id"] == "T1")
    assert len(t1["notes"]) == 2  # original note kept
    assert t1["notes"][-1] == {
        "note_id": "N9", "author": "Bob", "message": "looking into it"}


def test_add_note_saves_exactly_once(mocks):
    add_note("T1", "Bob", "looking into it")
    mocks["save"].assert_called_once()


def test_add_note_keeps_every_ticket_exactly_once(mocks):
    add_note("T1", "Bob", "looking into it")

    saved = mocks["save"].call_args[0][0]
    assert sorted(t["id"] for t in saved) == ["T1", "T2", "T3"]


def test_add_note_leaves_other_tickets_untouched(mocks):
    add_note("T1", "Bob", "looking into it")

    saved = mocks["save"].call_args[0][0]
    t3 = next(t for t in saved if t["id"] == "T3")
    assert t3["notes"] == []


def test_add_note_works_on_in_progress_ticket(mocks):
    assert add_note("T3", "Bob", "update") == "Note added successfully! "


# ---------- add_note: validation ----------

def test_add_note_validates_author_and_message(mocks):
    add_note("T1", "Bob", "looking into it")
    mocks["validate"].assert_called_once_with("Bob", "looking into it")


def test_add_note_invalid_entry_returns_error_message(mocks):
    mocks["validate"].side_effect = ValueError("author cannot be empty")

    assert add_note("T1", "", "looking into it") == "\nError: author cannot be empty"


def test_add_note_invalid_entry_saves_nothing(mocks):
    mocks["validate"].side_effect = ValueError("author cannot be empty")

    add_note("T1", "", "looking into it")

    mocks["save"].assert_not_called()


# ---------- add_note: resolved tickets ----------

def test_add_note_on_resolved_ticket_returns_none(mocks):
    assert add_note("T2", "Bob", "one more thing") is None


def test_add_note_on_resolved_ticket_prints_warning(mocks, capsys):
    add_note("T2", "Bob", "one more thing")

    assert "Cannot add a note to a resolved ticket" in capsys.readouterr().out


def test_add_note_on_resolved_ticket_saves_nothing(mocks, stored_tickets):
    add_note("T2", "Bob", "one more thing")

    mocks["save"].assert_not_called()
    t2 = next(t for t in stored_tickets if t["id"] == "T2")
    assert t2["notes"] == []


# ---------- add_note: bad ids ----------

def test_add_note_unknown_ticket_raises(mocks):
    with pytest.raises(ValueError):
        add_note("INVALID", "Bob", "hello")
    mocks["save"].assert_not_called()


def test_add_note_wrong_case_id_is_rejected(mocks):
    # "t1" is not the id that was generated ("T1"), so it must not work
    with pytest.raises(ValueError):
        add_note("t1", "Bob", "looking into it")
    mocks["save"].assert_not_called()


# ---------- note_display ----------

def test_note_display_returns_ticket(mocks, stored_tickets):
    assert note_display("T1") is stored_tickets[0]
    mocks["find"].assert_called_once_with("T1")


def test_note_display_unknown_ticket_raises(mocks):
    with pytest.raises(ValueError):
        note_display("INVALID")